static void oled_cmd(i2c_master_dev_handle_t handle, uint8_t cmd) {
    uint8_t buf[2] = {0x00, cmd};
    i2c_master_transmit(handle, buf, 2, -1);
}

static void oled_init(i2c_master_dev_handle_t handle) {
    uint8_t init_cmds[] = { 0xAE, 0x20, 0x00, 0x21, 0x00, 0x7F, 0x22, 0x00, 0x07, 0x8D, 0x14, 0xAF };
    for (int i = 0; i < sizeof(init_cmds); i++) oled_cmd(handle, init_cmds[i]);
}

static void oled_clear(i2c_master_dev_handle_t handle) {
    uint8_t empty[129] = {0x40}; // 0x40 = data byte, rest are 0s
    for (uint8_t p = 0; p < 8; p++) {
        oled_cmd(handle, 0xB0 + p); oled_cmd(handle, 0x00); oled_cmd(handle, 0x10);
        i2c_master_transmit(handle, empty, 129, -1);
    }
}

static void oled_print(i2c_master_dev_handle_t handle, uint8_t col, uint8_t page, const char *str) {
    oled_cmd(handle, 0xB0 + page);
    oled_cmd(handle, 0x00 + (col & 0x0F));
    oled_cmd(handle, 0x10 + ((col >> 4) & 0x0F));
    
    uint8_t buf[129] = {0x40}; // 0x40 означает, что дальше идут данные
    int buf_idx = 1;
    
    while (*str && buf_idx < 120) {
        if (*str >= 32 && *str <= 127) {
            for (int i = 0; i < 5; i++) buf[buf_idx++] = font5x7[*str - 32][i];
            buf[buf_idx++] = 0x00; // Пробел между буквами
        }
        str++;
    }
    i2c_master_transmit(handle, buf, buf_idx, -1);
}